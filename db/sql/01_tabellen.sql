  GEAENDERT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT RH_QUELLE_PK PRIMARY KEY (ID),
  CONSTRAINT RH_QUELLE_UK UNIQUE (KURZ),
  CONSTRAINT RH_QUELLE_ART_CK CHECK (ART IN ('WEB','BUCH','ARTIKEL','DATEN','MESSUNG')),
  CONSTRAINT RH_QUELLE_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT','EIGEN'))
