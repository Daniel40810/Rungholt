CREATE OR REPLACE TRIGGER RH_QUELLE_BIU
BEFORE INSERT OR UPDATE ON RH_QUELLE
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.ID IS NULL THEN
      :NEW.ID := RH_QUELLE_SEQ.NEXTVAL;
    END IF;
    :NEW.ANGELEGT := NVL(:NEW.ANGELEGT, SYSTIMESTAMP);
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
