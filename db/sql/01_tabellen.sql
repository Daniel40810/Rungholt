-- Schema RUNGHOLT auf PDBORCL, Präfix RH_. Werkbuch Abschnitt 8, freigegeben am 20.10.2026 (F25–F36 „alle A“).
--
-- Wiederholbar: Was schon da ist, meldet Oracle mit ORA-00955 (Name schon vergeben); der Einrichter der App
-- übergeht genau diese Meldung. In SQL Developer als Skript ausführen (F5); die Meldungen bei einem zweiten
-- Lauf sind dann harmlos. Dieses Skript löscht nichts.
--
-- Hauskonvention: ID aus Sequence + Trigger, nie GENERATED AS IDENTITY. Je Spalte eine Zeile, damit der
-- Einrichter fehlende Spalten erkennen und nachtragen kann. Lage in 8307 (Länge, Breite), daneben Szenenmeter
-- X_M, Z_M (x nach Osten, z nach Süden, Ursprung an der Kirche [G]).
-- Szenenzeit (F33): SZENE_MS = Millisekunden seit 1970 (UTC), proleptisch gregorianisch wie die Uhr der App;
-- SZENE_TEXT so, wie die App sie zeigt („15.1.1362 18:36 Ortszeit“); SZENE_TAG = 'JJJJ-MM-TT' für Filter. Oracle
-- rechnet vor dem 15.10.1582 julianisch; ein TIMESTAMP für 1362 läge um 8 Tage daneben. Die Sichten geben ab 1583
-- zusätzlich SZENENZEIT als TIMESTAMP in deutscher Zeit.
-- 27 Tabellen in acht Themen: Betrieb, Quellen, Gelände, Tide, Chronik, Rungholt, Regie, Kamera und Packages.
-- =====================================================================================================


